export function getAcademyCopy(locale: Locale): AcademyUiCopy {
  return locale === "en" ? en : translations[locale];
}

export function getAcademyResultLabel(locale: Locale, count: number) {
  if (locale === "en") return count === 1 ? "lesson" : "lessons";
  if (locale === "de") return count === 1 ? "Lektion" : "Lektionen";
  if (locale === "es") return count === 1 ? "lección" : "lecciones";
  if (locale === "fr") return count === 1 ? "leçon" : "leçons";
  if (locale === "pt") return count === 1 ? "lição" : "lições";
  if (locale === "ar") return count === 1 ? "درس" : "دروس";
  if (locale === "ru") {
    const category = new Intl.PluralRules("ru").select(count);
    if (category === "one") return "урок";
    if (category === "few") return "урока";
    return "уроков";
  }
  return translations[locale].resultCount;
}
