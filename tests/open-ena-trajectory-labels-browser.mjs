async function stable(view, timeoutMs = 30_000) {
  if (view === "3d") await plotRoot().filter({ has: page.locator("canvas") }).waitFor();
  await page.waitForFunction(async view => {
    const snapshot = () => {
      if (view === "3d") {
        const root = document.querySelector('[data-ena-plotly-root="true"]');
        if (root?.getAttribute("data-ena-label-layout") !== "ready") return null;
        const nodes = [...root.querySelectorAll("g.annotation-scene[data-ena-label-id]")];
        if (!nodes.length || nodes.length !== root.querySelectorAll("g.annotation-scene").length) return null;
        return JSON.stringify(nodes.map(node => { const r = node.getBoundingClientRect(); return [node.getAttribute("data-ena-label-id"), node.getAttribute("data-ena-label-visible"), r.x, r.y, r.width, r.height]; }));
      }
      const nodes = [...document.querySelectorAll('[data-ena-label-box="true"]')];
      if (!nodes.some(node => Number(node.getAttribute("data-label-width")) > 0)) return null;
      return JSON.stringify(nodes.map(node => [...node.attributes].map(attr => [attr.name, attr.value])));
    };
    const before = snapshot(); if (before === null) return false;
    for (let i = 0; i < 3; i++) await new Promise(resolve => requestAnimationFrame(resolve));
    return before === snapshot();
  }, view, { timeout: timeoutMs });
}
function assertBoxes(labels, bounds, message) {
  const shown = labels.filter(label => label.visible);
  assert.ok(shown.length > 0, `${message}: no visible labels`);
  for (let i = 0; i < shown.length; i++) {
    const a = shown[i];
    assert.ok(a.width > 0 && a.height > 0, `${message}: ${a.id} has no measured size`);
    assert.ok(a.x >= bounds.x - 1 && a.y >= bounds.y - 1 && a.x + a.width <= bounds.x + bounds.width + 1 && a.y + a.height <= bounds.y + bounds.height + 1,
      `${message}: ${a.id} is clipped: ${JSON.stringify({ a, bounds })}`);
    for (const b of shown.slice(i + 1)) {
      const overlapX = Math.min(a.x + a.width, b.x + b.width) - Math.max(a.x, b.x);
      const overlapY = Math.min(a.y + a.height, b.y + b.height) - Math.max(a.y, b.y);
      assert.ok(overlapX <= 0.5 || overlapY <= 0.5, `${message}: ${a.id} overlaps ${b.id} by ${overlapX.toFixed(2)} × ${overlapY.toFixed(2)} px`);
    }
  }
}
async function audit2d({ all = false } = {}) {
  await stable("2d");
  const result = await svgRoot().evaluate(svg => {
    const rect = element => { const r = element.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; };
    return {
      bounds: rect(svg),
      axisLabels: [...svg.querySelectorAll(".ena-zero-axes text, .ena-three-axes text")].map(node => ({ text: node.textContent, ...rect(node) })),
      labels: [...svg.querySelectorAll('[data-ena-label-box="true"]')].map(node => {
        const text = node.querySelector("text[data-ena-layout-label]");
        return { id: node.getAttribute("data-label-id"), text: text?.textContent ?? "", visible: node.getAttribute("data-label-visible") === "true",
          layoutX: Number(node.getAttribute("data-label-x")), layoutY: Number(node.getAttribute("data-label-y")), ...rect(text ?? node) };
      }),
      titles: [...svg.querySelectorAll('[data-ena-trajectory-centroid="true"] title')].map(node => node.textContent),
      codeNodes: [...svg.querySelectorAll('[data-ena-code]')].map(node => ({ code: node.getAttribute("data-ena-code"), title: node.querySelector("title")?.textContent ?? node.parentElement.querySelector("title")?.textContent ?? "", fill: getComputedStyle(node).fill, radius: Number(node.getAttribute("r")) })),
      geometry: [...svg.querySelectorAll('[data-ena-code-node-position], [data-ena-trajectory-centroid] rect, [data-ena-trajectory-path], [data-ena-centroid-path]')].map(node => [node.tagName, ...["transform", "x", "y", "x1", "x2", "y1", "y2", "width", "height"].map(key => node.getAttribute(key))]),
    };
  });
  assertBoxes(result.labels, result.bounds, "2D");
  for (const label of result.labels.filter(label => label.visible)) for (const axis of result.axisLabels) {
    const overlapX = Math.min(label.x + label.width, axis.x + axis.width) - Math.max(label.x, axis.x);
    const overlapY = Math.min(label.y + label.height, axis.y + axis.height) - Math.max(label.y, axis.y);
    assert.ok(overlapX <= 0.5 || overlapY <= 0.5, `2D: ${label.id} intersects axis text ${axis.text}`);
  }
  const centroids = result.labels.filter(label => label.id.startsWith("centroid:"));
  assert.ok(centroids.length > 0);
  assert.ok(centroids.every(label => /^TP[123]$/.test(label.text)), "2D visible time text must consist only of the source value");
  assert.ok(result.titles.every(text => /Horizon Period=TP[123]/.test(text) && /n\s*=\s*\d+/.test(text) && /Group/.test(text)), "2D hover preserves full group/Horizon/count");
  if (all) assert.equal(result.labels.filter(label => !label.visible).length, 0, "default sample must retain every Code and Horizon label");
  return result;
}
async function audit3d({ all = false } = {}) {
  let result;
  const deadline = Date.now() + 30_000;
  while (Date.now() < deadline) {
  await stable("3d", Math.max(1, deadline - Date.now()));
  result = await plotRoot().evaluate(root => {
    const rect = element => { const r = element.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; };
    const annotations = root._fullLayout.scene.annotations;
    return {
      ready: root.getAttribute("data-ena-label-layout") === "ready",
      nativeAnnotationCount: root.querySelectorAll("g.annotation-scene").length,
      bounds: rect(root),
      projectionError: root.getAttribute("data-ena-label-projection-error"),
      labels: [...root.querySelectorAll("g.annotation-scene[data-ena-label-id]")].map(node => {
        const a = annotations[Number(node.getAttribute("data-index"))];
        const background = node.querySelector(".annotation-text-g .bg");
        return { id: node.getAttribute("data-ena-label-id"), role: node.getAttribute("data-ena-label-role"), text: node.querySelector(".annotation-text")?.textContent ?? "", visible: node.getAttribute("data-ena-label-visible") === "true", hover: a.hovertext, ...rect(background ?? node) };
      }),
      camera: root._fullLayout.scene._scene.getCamera(),
      codeNodeSize: root.data.find(trace => trace.meta?.role === "code-node")?.marker?.size,
      geometry: root.data.filter(trace => !["code-label", "axis-label"].includes(trace.meta?.role)).map(trace => ({ role: trace.meta?.role, x: trace.x, y: trace.y, z: trace.z, u: trace.u, v: trace.v, w: trace.w })),
    };
  });
  // Native fullscreen resize can start a new GL redraw after the preceding
  // condition resolved. Only audit an atomic, fully decorated ready snapshot.
  if (result.ready && result.labels.length > 0 && result.labels.length === result.nativeAnnotationCount) break;
  }
  assert.ok(result?.ready && result.labels.length === result.nativeAnnotationCount, "3D annotation layout did not settle");
  assertBoxes(result.labels, result.bounds, "3D");
  assert.ok(result.projectionError !== null && Number.isFinite(Number(result.projectionError)) && Number(result.projectionError) < 0.5,
    `native projection adapter differs from annotation anchors: ${result.projectionError}`);
  const centroids = result.labels.filter(label => label.role === "centroid");
  assert.ok(centroids.length > 0);
  assert.ok(centroids.every(label => /^TP[123]$/.test(label.text)), "3D time text must consist only of the source value");
  assert.ok(centroids.every(label => /Horizon Period=TP[123]/.test(label.hover) && /n\s*=\s*\d+/.test(label.hover) && /Group/.test(label.hover)), "3D hover preserves full group/Horizon/count");
  if (all) assert.equal(result.labels.filter(label => !label.visible).length, 0, "default sample must retain every Code and Horizon label");
  return result;
}
