async function hover3dCode(name) {
  const point = await plotRoot().evaluate((root, name) => {
    const scene = root._fullLayout.scene, size = root._fullLayout._size;
    const trace = root._fullData.find(trace => trace.meta?.role === "code-node");
    const index = trace?.text?.indexOf(name);
    if (!(index >= 0)) throw new Error(`Missing scientific Code node ${name}`);
    const scale = scene._scene.dataScale, matrices = scene._scene.glplot.cameraParams;
    let vector = [scene.xaxis.r2l(trace.x[index]) * scale[0], scene.yaxis.r2l(trace.y[index]) * scale[1], scene.zaxis.r2l(trace.z[index]) * scale[2], 1];
    for (const matrix of [matrices.model, matrices.view, matrices.projection]) vector = [0, 1, 2, 3].map(row => matrix[row] * vector[0] + matrix[row + 4] * vector[1] + matrix[row + 8] * vector[2] + matrix[row + 12] * vector[3]);
    const domain = scene.domain, rect = root.getBoundingClientRect();
    const x = size.l + domain.x[0] * size.w + (1 + vector[0] / vector[3]) / 2 * size.w * (domain.x[1] - domain.x[0]);
    const y = size.t + (1 - domain.y[1]) * size.h + (1 - vector[1] / vector[3]) / 2 * size.h * (domain.y[1] - domain.y[0]);
    return { x: rect.x + x * rect.width / root._fullLayout.width, y: rect.y + y * rect.height / root._fullLayout.height };
  }, name);
  await page.mouse.move(point.x, point.y);
  await page.waitForFunction(name => [...document.querySelectorAll(".hovertext")].some(node => node.textContent.includes(name)), name);
  const tooltip = await page.locator(".hovertext").allTextContents();
  await page.mouse.move(10, 10);
  return tooltip;
}
