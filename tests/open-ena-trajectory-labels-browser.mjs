async function tinyDrag3d() {
  const nativeSnapshot = () => plotRoot().evaluate(root => {
    const annotations = root._fullLayout.scene.annotations;
    const annotation = annotations.find(a => a.text === "TE");
    const trace = root.data.find(t => t.meta?.role === "code-label");
    const index = trace?.text?.indexOf("TE");
    const r = root.getBoundingClientRect();
    const element = root.querySelector(`g.annotation-scene[data-index="${annotations.indexOf(annotation)}"]`);
    const rect = node => { const value = node?.getBoundingClientRect(); return value && { x: value.x, y: value.y, width: value.width, height: value.height }; };
    const background = rect(element?.querySelector(".annotation-text-g .bg"));
    const anchor = annotation && [annotation._xa._offset + annotation._xa.r2p(annotation.x), annotation._ya._offset + annotation._ya.r2p(annotation.y)];
    return { bounds: { x: r.x, y: r.y, width: r.width, height: r.height }, width: root._fullLayout.width, height: root._fullLayout.height,
      size: root._fullLayout._size, dataScale: Array.from(root._fullLayout.scene._scene.dataScale),
      background, text: rect(element?.querySelector(".annotation-text")),
      actualCenterLayout: background && [(background.x + background.width / 2 - r.x) * root._fullLayout.width / r.width, (background.y + background.height / 2 - r.y) * root._fullLayout.height / r.height],
      declarativeCenterLayout: anchor && [anchor[0] + annotation.ax, anchor[1] + annotation.ay],
      annotation: annotation && { x: annotation.x, y: annotation.y, z: annotation.z, ax: annotation.ax, ay: annotation.ay,
        anchor },
      trace: index >= 0 ? { x: trace.x[index], y: trace.y[index], z: trace.z[index] } : null,
      camera: root._fullLayout.scene._scene.getCamera() };
  });
  const label = plotRoot().locator('g.annotation-scene[data-ena-label-role="code"][data-ena-label-visible="true"] .annotation-text').filter({ hasText: /^TE$/ });
  await label.scrollIntoViewIfNeeded();
  const before = await label.boundingBox(); assert.ok(before);
  const nativeBefore = await nativeSnapshot();
  const diagnostic = { before, nativeBefore };
  (report.dragDiagnostics ??= []).push(diagnostic);
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2);
  const nativeHover = await nativeSnapshot();
  diagnostic.nativeHover = nativeHover;
  await page.mouse.down(); const nativeDown = await nativeSnapshot();
  diagnostic.nativeDown = nativeDown;
  await page.mouse.move(before.x + before.width / 2 + 3, before.y + before.height / 2);
  await stable("3d");
  const nativeAfter = await nativeSnapshot();
  diagnostic.nativeAfter = nativeAfter;
  assert.deepEqual(nativeAfter.dataScale, nativeBefore.dataScale, "manual text anchors must not renormalize the scientific 3D scene");
  assert.deepEqual([nativeAfter.annotation.x, nativeAfter.annotation.y, nativeAfter.annotation.z], [nativeBefore.annotation.x, nativeBefore.annotation.y, nativeBefore.annotation.z], "annotation anchors stay on their canonical scientific Code node");
  const after = await label.boundingBox(); assert.ok(after); await page.mouse.up();
  diagnostic.after = after;
  assert.ok(Math.abs(after.x - before.x - 3) <= 2 && Math.abs(after.y - before.y) <= 2,
    `a 3 px 3D Code-label drag must not jump: ${JSON.stringify({ before, after, nativeBefore, nativeHover, nativeDown, nativeAfter })}`);
  await resetLabels(); await audit3d();
}

