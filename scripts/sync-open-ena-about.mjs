#!/usr/bin/env node
// OPEN-ENA owns the About source. ENA consumes a generated, deployable snapshot.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const sourceArg = args.indexOf("--source");
if (sourceArg !== -1 && (!args[sourceArg + 1] || args[sourceArg + 1].startsWith("--"))) {
  throw new Error("--source requires an OPEN-ENA checkout path");
}
const source = path.resolve(sourceArg === -1 ? path.join(root, "../OPEN-ENA") : args[sourceArg + 1]);
const componentDir = "components/about/open-ena";
const sources = [
  ["components/about/AboutContent.tsx", "AboutContent.tsx"],
  ["components/about/AboutContent.module.css", "AboutContent.module.css"],
  ["components/TeamCard.tsx", "TeamCard.tsx"],
  ["components/PublicationCard.tsx", "PublicationCard.tsx"],
  ["lib/team.ts", "team.ts"],
  ["lib/publications.ts", "publications.ts"],
];
const outputs = new Map();
const hashes = {};
const assets = new Set();
const hash = (value) => createHash("sha256").update(value).digest("hex");

for (const [input, filename] of sources) {
  const raw = await readFile(path.join(source, input), "utf8");
  hashes[input] = hash(raw);
  for (const match of raw.matchAll(/"(\/(?:team\/|publications\/|logo-open-ena-mark\.svg)[^"\s]*)"/g)) {
    assets.add(match[1]);
  }
  const generated = raw
    .replaceAll("@/components/PublicationCard", "./PublicationCard")
    .replaceAll("@/components/TeamCard", "./TeamCard")
    .replaceAll("@/lib/publications", "./publications")
    .replaceAll("@/lib/team", "./team")
    .replaceAll("./about/AboutContent.module.css", "./AboutContent.module.css")
    .replace(/"(\/(?:team\/|publications\/|logo-open-ena-mark\.svg)[^"\s]*)"/g, '"/open-ena-about$1"')
    .replace('`https://www.open-ena.com${publication.cover}`', '`https://www.open-ena.com${publication.cover.replace("/open-ena-about", "")}`');
  const notice = filename.endsWith(".css")
    ? "/* Generated by scripts/sync-open-ena-about.mjs. Edit OPEN-ENA source instead. */\n"
    : "// Generated by scripts/sync-open-ena-about.mjs. Edit OPEN-ENA source instead.\n";
  outputs.set(`${componentDir}/${filename}`, Buffer.from(notice + generated));
}

for (const asset of [...assets].sort()) {
  if (asset.includes("..")) throw new Error(`Invalid About asset path: ${asset}`);
  const input = `public${asset}`;
  const bytes = await readFile(path.join(source, input));
  hashes[input] = hash(bytes);
  outputs.set(`public/open-ena-about${asset}`, bytes);
}
outputs.set(`${componentDir}/source-manifest.json`, Buffer.from(JSON.stringify({
  source: "https://www.open-ena.com/about",
  generator: "scripts/sync-open-ena-about.mjs",
  files: hashes,
}, null, 2) + "\n"));

const differences = [];
for (const [relative, bytes] of outputs) {
  const destination = path.join(root, relative);
  if (check) {
    const existing = await readFile(destination).catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (!existing?.equals(bytes)) differences.push(relative);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }
}
if (differences.length) {
  console.error(`About snapshot differs from OPEN-ENA:\n${differences.join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(`${check ? "Verified" : "Generated"} ${outputs.size} About files (${assets.size} local assets).`);
}
